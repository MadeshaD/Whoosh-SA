inline float windWeight(unsigned layer,float ratio) {
    if(layer==4)return .23f*ratio;
    if(layer>=3)return 0;
    float at=std::clamp(ratio,0.f,1.f)*127.f;
    unsigned i=static_cast<unsigned>(at);
    float a=windCurves[layer][i],b=windCurves[layer][std::min(i+1,127u)];
    return (a+(b-a)*(at-i))/32767.f;
}
// The unpadded name from Assets 3 takes precedence over the 0.3 spelling.
inline int windNumber(std::wstring_view name,bool& canonical) {
    canonical=false;
    if(name.size()!=10 && name.size()!=11)return 0;
    auto lower=[](wchar_t c){return c>=L'A' && c<=L'Z'?c+(L'a'-L'A'):int(c);};
    constexpr wchar_t prefix[]=L"wind ",suffix[]=L".wav";
    for(unsigned i=0;i<5;i++)if(lower(name[i])!=prefix[i])return 0;
    size_t digit=name.size()-5;
    if(digit==6 && name[5]!=L'0')return 0;
    for(unsigned i=0;i<4;i++)if(lower(name[digit+1+i])!=suffix[i])return 0;
    if(name[digit]<L'1' || name[digit]>L'5')return 0;
    canonical=digit==5;
    return name[digit]-L'0';
}
